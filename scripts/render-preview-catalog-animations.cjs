"use strict";
const {mkdirSync, existsSync} = require("node:fs");
const {spawn} = require("node:child_process");
const {join} = require("node:path");
const root = process.cwd();
const layouts = ["person-rank","event-timeline","pivot-list","value-verdict","capital-dashboard","cook-machine","engineering-return","market-battlefield","finale-kinetic","reject-list","check-progress","diagonal-chips","floating-chips","bare-typography","chapter-card","logo-wordmark","ordered-sequence","org-chart","draw-line","progress-donut","avatar-handoff","bull-bear","opinion-hero","photo-wall","product-explosion","newspaper-swap","route-map","data-flow","screen-recording","zoom-statement","desktop-folders","time-rewind","clipboard-note","closing-checklist","platform-shift-line","tradeoff-reject-round","recovery-progress-bars","hud-glow-stack","briefing-poster","rewind-milestones","flying-paper-stack","checklist-editorial","spotlight-question"];
const fps = 30;
const sceneFrames = 150;
const previewFrames = 120;
const force = process.argv.includes("--force");
const onlyArg = process.argv.find((arg) => arg.indexOf("--only=") === 0);
const selectedLayouts = onlyArg ? layouts.filter((layout) => onlyArg.slice(7).split(",").includes(layout)) : layouts;
const outDir = join(root, "public", "preview-catalog-animation");
mkdirSync(outDir, {recursive: true});
const render = (layout, index) => new Promise((resolve, reject) => {
  const output = join(outDir, layout + ".mp4");
  if (existsSync(output) && !force) return resolve({layout, cached: true});
  const start = index * sceneFrames;
  const end = start + previewFrames - 1;
  const child = spawn(join(root, "node_modules", ".bin", "remotion.CMD"), ["render", "src/index.ts", "JasonWuComponentCatalog", output, "--frames=" + start + "-" + end, "--codec=h264", "--crf=26", "--pixel-format=yuv420p", "--concurrency=2"], {cwd: root, windowsHide: true, shell: true});
  let error = "";
  child.stderr.on("data", (chunk) => error = (error + chunk).slice(-3000));
  child.on("error", reject);
  child.on("close", (code) => code === 0 ? resolve({layout, cached: false}) : reject(new Error(layout + ": " + (error || "render exited " + code))));
});
const workers = Math.min(2, selectedLayouts.length);
let cursor = 0;
const run = async () => { const results = []; const worker = async () => { while (cursor < selectedLayouts.length) { const layout = selectedLayouts[cursor++]; const index = layouts.indexOf(layout); const result = await render(layout, index); console.log(JSON.stringify(result)); results.push(result); } }; await Promise.all(Array.from({length: workers}, worker)); console.log(JSON.stringify({completed: results.length, outDir})); };
run().catch((error) => { console.error(error.stack || error.message); process.exit(1); });
